// Token Radar's model, version radar-2: one snapshot of the protocol universe in, one ranked board out.
//
// The board ranks every genuine pre-token launch candidate the snapshot holds: a protocol
// that records no token and is not a wrapped, staked or bridged product of a token that
// already trades. The snapshot's watchlist is the floor (40 protocols at or above $50M of
// TVL); the early radar extends the same filter below the floor, so the board also finds
// the small protocols a token launch would matter most for.
//
// Implied value is derived from the snapshot's own figures, never from a list of names:
//
//   benchmark  = the category's median market-cap / TVL among the protocols in this
//                snapshot whose token already trades, shrunk toward the global median
//                with 3 pseudo-observations, clamped to [0.05, 1.5]. A category needs at
//                least 3 live protocols to set its own benchmark; a thinner category uses
//                the global median, so one outlier never sets a whole category's multiple.
//                Individual ratios are winsorised at 5 before the median is taken.
//   growthMult = 1 + clamp(change_7d, -50, 100) / 100 x 0.5
//   maturity   = 0.6 + min(age_days, 1095) / 1095 x 0.4   (age unknown: 365 days)
//   implied    = max(1, round(tvl_usd x benchmark x growthMult x maturity))
//
// A category whose live protocols trade richly against their TVL (bridges, basis trading)
// gives its pre-token peers a higher multiple than one whose live protocols trade thinly
// (liquid staking). The dashboard shows the benchmark table, so a reader can check the
// arithmetic instead of taking the ranking on trust.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

